def parse_hex_color(hex_str, alpha=255):
    hex_str = hex_str.lstrip('#')
    if len(hex_str) == 3:
        r = int(hex_str[0] * 2, 16)
        g = int(hex_str[1] * 2, 16)
        b = int(hex_str[2] * 2, 16)
        return (r, g, b, alpha)
    elif len(hex_str) == 6:
        r = int(hex_str[0:2], 16)
        g = int(hex_str[2:4], 16)
        b = int(hex_str[4:6], 16)
        return (r, g, b, alpha)
    elif len(hex_str) == 8:
        r = int(hex_str[0:2], 16)
        g = int(hex_str[2:4], 16)
        b = int(hex_str[4:6], 16)
        a = int(hex_str[6:8], 16)
        return (r, g, b, a)
    return (255, 255, 255, alpha)

class PureCanvas:
    def __init__(self, width: int, height: int, bg_color="#1a1a2e"):
        self.width = width
        self.height = height
        self.bg = parse_hex_color(bg_color)
        # Byte array for RGBA pixels
        self.pixels = bytearray(self.bg * (width * height))

    def set_pixel(self, x: int, y: int, color):
        if 0 <= x < self.width and 0 <= y < self.height:
            idx = (y * self.width + x) * 4
            sr, sg, sb, sa = color
            if sa == 255:
                self.pixels[idx] = sr
                self.pixels[idx+1] = sg
                self.pixels[idx+2] = sb
                self.pixels[idx+3] = 255
            elif sa > 0:
                dr = self.pixels[idx]
                dg = self.pixels[idx+1]
                db = self.pixels[idx+2]
                inv_a = 255 - sa
                self.pixels[idx] = (sr * sa + dr * inv_a) // 255
                self.pixels[idx+1] = (sg * sa + dg * inv_a) // 255
                self.pixels[idx+2] = (sb * sa + db * inv_a) // 255
                self.pixels[idx+3] = 255

    def fill_rect(self, x: int, y: int, w: int, h: int, color):
        x1 = max(0, int(x))
        y1 = max(0, int(y))
        x2 = min(self.width, int(x + w))
        y2 = min(self.height, int(y + h))
        if x2 <= x1 or y2 <= y1:
            return
        c = parse_hex_color(color) if isinstance(color, str) else color
        sr, sg, sb, sa = c
        if sa == 255:
            row_bytes = bytes([sr, sg, sb, 255]) * (x2 - x1)
            for cy in range(y1, y2):
                start_idx = (cy * self.width + x1) * 4
                self.pixels[start_idx : start_idx + len(row_bytes)] = row_bytes
        else:
            for cy in range(y1, y2):
                for cx in range(x1, x2):
                    self.set_pixel(cx, cy, c)

    def draw_rounded_rect(self, x: int, y: int, w: int, h: int, radius: int, fill_color, border_color=None, border_width=1):
        fc = parse_hex_color(fill_color) if isinstance(fill_color, str) else fill_color
        bc = parse_hex_color(border_color) if isinstance(border_color, str) and border_color else None
        
        x1 = int(x)
        y1 = int(y)
        x2 = int(x + w)
        y2 = int(y + h)
        r = min(radius, (x2 - x1) // 2, (y2 - y1) // 2)
        
        for cy in range(max(0, y1), min(self.height, y2)):
            for cx in range(max(0, x1), min(self.width, x2)):
                # Check 4 corner circles
                in_corner = False
                dist_sq = 0
                if cx < x1 + r and cy < y1 + r:
                    dx, dy = (x1 + r) - cx, (y1 + r) - cy
                    dist_sq = dx*dx + dy*dy
                    in_corner = True
                elif cx >= x2 - r and cy < y1 + r:
                    dx, dy = cx - (x2 - r - 1), (y1 + r) - cy
                    dist_sq = dx*dx + dy*dy
                    in_corner = True
                elif cx < x1 + r and cy >= y2 - r:
                    dx, dy = (x1 + r) - cx, cy - (y2 - r - 1)
                    dist_sq = dx*dx + dy*dy
                    in_corner = True
                elif cx >= x2 - r and cy >= y2 - r:
                    dx, dy = cx - (x2 - r - 1), cy - (y2 - r - 1)
                    dist_sq = dx*dx + dy*dy
                    in_corner = True
                
                if in_corner and dist_sq > r * r:
                    continue
                
                # Check border
                if bc:
                    is_border = False
                    if in_corner and dist_sq >= (r - border_width) * (r - border_width):
                        is_border = True
                    elif not in_corner and (cx < x1 + border_width or cx >= x2 - border_width or cy < y1 + border_width or cy >= y2 - border_width):
                        is_border = True
                    
                    if is_border:
                        self.set_pixel(cx, cy, bc)
                        continue
                        
                self.set_pixel(cx, cy, fc)

    def draw_line(self, x1: int, y1: int, x2: int, y2: int, color, stroke_width=1, dashed=False, dash_len=8):
        c = parse_hex_color(color) if isinstance(color, str) else color
        dx = x2 - x1
        dy = y2 - y1
        steps = int(max(abs(dx), abs(dy)))
        if steps == 0:
            self.set_pixel(int(x1), int(y1), c)
            return
        x_inc = dx / steps
        y_inc = dy / steps
        cx = float(x1)
        cy = float(y1)
        
        half_w = stroke_width // 2
        for s in range(steps + 1):
            if not dashed or ((s // dash_len) % 2 == 0):
                ix, iy = int(round(cx)), int(round(cy))
                for ox in range(-half_w, half_w + 1):
                    for oy in range(-half_w, half_w + 1):
                        self.set_pixel(ix + ox, iy + oy, c)
            cx += x_inc
            cy += y_inc

    def draw_text(self, x: int, y: int, text: str, font_size=16, color="#ffffff", bold=False, align="left"):
        c = parse_hex_color(color) if isinstance(color, str) else color
        scale = max(1, font_size // 12)
        char_w = 8 * scale
        char_h = 12 * scale
        total_w = len(text) * char_w
        
        if align == "center":
            start_x = int(x - total_w // 2)
        elif align == "right":
            start_x = int(x - total_w)
        else:
            start_x = int(x)
            
        cur_x = start_x
        for ch in text:
            bitmap = FONT_8X12.get(ch, FONT_8X12.get('?'))
            if bitmap:
                for row_idx, byte_val in enumerate(bitmap):
                    for col_idx in range(8):
                        if (byte_val >> (7 - col_idx)) & 1:
                            px = cur_x + col_idx * scale
                            py = y + row_idx * scale
                            for sx in range(scale + (1 if bold else 0)):
                                for sy in range(scale):
                                    self.set_pixel(px + sx, py + sy, c)
            cur_x += char_w

    def save_png(self, filepath: str):
        # Build standard PNG file format
        raw_data = bytearray()
        stride = self.width * 4
        for y in range(self.height):
            raw_data.append(0)  # Filter type 0 (None)
            idx = y * stride
            raw_data.extend(self.pixels[idx : idx + stride])
            
        compressed = zlib.compress(bytes(raw_data), level=9)
        
        def make_chunk(chunk_type: bytes, data: bytes) -> bytes:
            chunk = chunk_type + data
            crc = zlib.crc32(chunk) & 0xffffffff
            return struct.pack(">I", len(data)) + chunk + struct.pack(">I", crc)
        
        # PNG Signature
        header = b"\x89PNG\r\n\x1a\n"
        # IHDR: width(4), height(4), bit_depth(1), color_type(6=RGBA), compression(0), filter(0), interlace(0)
        ihdr_data = struct.pack(">IIBBBBB", self.width, self.height, 8, 6, 0, 0, 0)
        ihdr_chunk = make_chunk(b"IHDR", ihdr_data)
        idat_chunk = make_chunk(b"IDAT", compressed)
        iend_chunk = make_chunk(b"IEND", b"")
        
        with open(filepath, "wb") as f:
            f.write(header + ihdr_chunk + idat_chunk + iend_chunk)
            
        print(f"[✔] Successfully saved pure PNG image ({self.width}x{self.height}) → {filepath}")
